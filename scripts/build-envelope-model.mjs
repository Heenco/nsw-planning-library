/**
 * Build a planning-envelope model for the 3D viewer, from a real Hornsby lot.
 *
 * Connects the three things we hold for one property:
 *
 *   nsw.up_property_d_3   the lot itself — area, frontage, depth, mapped HOB
 *   LEP Part 4 (cl 4.3)   height standard, where the clause carries a number
 *   Hornsby DCP           the setback and height planes, by land use and storeys
 *
 * and emits the box geometry the viewer reads, with every plane named after the
 * clause that sets it — click a plane in the viewer and its source is the label.
 *
 * This is NOT a NSW Housing Pattern Book design. The Pattern Book's dimensions
 * live in its downloadable pattern packs, which we do not hold. What the massing
 * shows is a two-storey form sized to fit the envelope, so the question it
 * answers is "what does this lot allow", not "here is an approved design".
 *
 *   node scripts/build-envelope-model.mjs
 *   node scripts/build-envelope-model.mjs --address "100 GALSTON ROAD HORNSBY HEIGHTS"
 *   node scripts/build-envelope-model.mjs --address "..." --use "dual occupancy" --storeys 2
 */

import 'dotenv/config'
import pg from 'pg'
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { buildEnvelopeModel, buildEnvelopeRationale } from '../shared/envelope-model.mjs'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const viewer = join(root, 'public', 'craftbot-viewer', 'models')

// ── args ────────────────────────────────────────────────────────────────────

const argv = process.argv.slice(2)
const arg = (name, fallback = null) => {
  const i = argv.indexOf(`--${name}`)
  return i >= 0 && argv[i + 1] ? argv[i + 1] : fallback
}
const ADDRESS = arg('address', '100 GALSTON ROAD HORNSBY HEIGHTS')
const LAND_USE = arg('use', 'dwelling house')
const STOREYS = Number(arg('storeys', '2'))

// ── data ────────────────────────────────────────────────────────────────────

const pool = new pg.Pool({ connectionString: (process.env.DATABASE_URL || '').trim(), max: 2 })
const q = async (sql, params = []) => (await pool.query(sql, params)).rows

const lot = (await q(
  `SELECT address, lot_section_plan, suburbname, area_sqm, primary_frontage_length_m,
          lot_depth_m, is_corner_lot, lzn_sym_code_p AS zone, hob_max_b_h_m, lot_size,
          epi_name, centroid_lat, centroid_lon
   FROM nsw.up_property_d_3 WHERE address = $1 LIMIT 1`, [ADDRESS]))[0]

if (!lot) { console.error(`No lot found for "${ADDRESS}"`); await pool.end(); process.exit(1) }

// Setback and height planes for this use at this number of storeys.
const controls = await q(
  `SELECT DISTINCT r.clause, e.topic, e.comparator, e.value::float8 value, e.measured_from
   FROM nsw.rule_applicability a
   JOIN nsw.rule r ON r.id = a.rule_id
   JOIN nsw.rule_effect e ON e.rule_id = r.id
   JOIN nsw.document d ON d.id = r.document_id
   WHERE d.doc_type='dcp' AND a.dimension='land_use' AND lower(a.value)=lower($1)
     AND e.topic IN ('setback','height') AND e.value IS NOT NULL
     AND ($2::numeric IS NULL OR e.condition_metric IS DISTINCT FROM 'storeys'
          OR ($2 >= COALESCE(e.condition_lo,-1e9) AND $2 <= COALESCE(e.condition_hi,1e9)))`,
  [LAND_USE, STOREYS])

await pool.end()

// ── build ───────────────────────────────────────────────────────────────────

// Geometry and rationale both come from shared/envelope-model.mjs, which is what
// /api/property/envelope serves. Duplicating them here once meant the batch
// output and the on-demand output could describe the same lot differently.
const { model, meta } = buildEnvelopeModel(lot, controls)
const rationale = buildEnvelopeRationale(meta, { landUse: LAND_USE, storeys: STOREYS })

const slug = String(lot.address).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')
const rel = `nsw/${slug}.json`
const ratRel = `nsw/${slug}_rationale.md`

mkdirSync(join(viewer, 'nsw'), { recursive: true })
const json = JSON.stringify(model)
writeFileSync(join(viewer, rel), json, 'utf-8')
writeFileSync(join(viewer, ratRel),
  `${rationale}
Generated by \`node scripts/build-envelope-model.mjs --address "${lot.address}"\`.
`,
  'utf-8')

const indexPath = join(viewer, 'index.json')
const index = JSON.parse(readFileSync(indexPath, 'utf-8'))
const id = `nsw_lot_${slug}`
index.experiments = index.experiments.filter(e => e.id !== id)
index.experiments.push({
  id,
  title: `NSW · ${lot.address}`,
  runs: [{ agent: 'Planning controls', rationale: ratRel,
    versions: [{ v: 'v01', file: rel, elements: model.boxes.length, bytes: json.length }] }],
})
writeFileSync(indexPath, JSON.stringify(index), 'utf-8')

const fmt = (n) => Number(n).toFixed(1)
console.log(`${meta.address}  [${meta.zone}]  ${meta.area_sqm} m², ${fmt(meta.width)} x ${fmt(meta.depth)} m`)
console.log(`  setbacks  front ${meta.front}  rear ${meta.rear}  side ${meta.side}   height ${meta.height} m (${meta.heightSource})`)
console.log(meta.buildable
  ? `  buildable ${fmt(meta.buildableWidth)} x ${fmt(meta.buildableDepth)} m  (${Math.round(meta.buildableWidth * meta.buildableDepth)} m²)`
  : `  NO BUILDABLE ENVELOPE — setbacks exceed the lot`)
console.log(`  ${model.boxes.length} elements -> models/${rel}`)
