<script setup lang="ts">
const VARIANTS = [
  { key: 'context', label: 'Contextual', blurb: 'what a council assessor would find unremarkable' },
  { key: 'yield', label: 'Maximum yield', blurb: 'take every square metre the controls allow' },
  { key: 'amenity', label: 'Amenity first', blurb: 'sun, outlook and open space over floor area' },
]

const MARK: Record<string, string> = { pass: '✓', fail: '✕', warn: '!', na: '–' }

/** A spread of lot shapes: regular, battle-axe, corner, rural, and a Randwick terrace. */
const samples = [
  { short: '100 Galston Rd', zone: 'R2', address: '100 GALSTON ROAD HORNSBY HEIGHTS' },
  { short: '307 Galston Rd', zone: 'RU4', address: '307 GALSTON ROAD GALSTON' },
  { short: '15 Mildred Ave', zone: 'R3', address: '15 MILDRED AVENUE HORNSBY' },
  { short: '63 Cowper St', zone: 'R3', address: '63 COWPER STREET RANDWICK' },
  { short: '903 Anzac Pde', zone: 'R2', address: '903 ANZAC PARADE MAROUBRA' },
]

const address = ref('')
const use = ref('dwelling house')
const storeys = ref(2)
const modelKey = ref('fable-5.1')
const variants = ref<string[]>(['context'])

const busy = ref(false)
const busyText = ref('')
const error = ref('')
const brief = ref<any>(null)
const results = ref<any[]>([])
const modelName = ref('')
const active = ref(0)

const current = computed(() => (active.value >= 0 ? results.value[active.value] : null))
const noRoom = computed(() => !!brief.value && (brief.value.buildableArea ?? 0) < 10)

const envelopeUrl = computed(() =>
  `/api/property/envelope?address=${encodeURIComponent(address.value)}&use=${encodeURIComponent(use.value)}&storeys=${storeys.value}`)

/**
 * The viewer takes a model URL and derives its rationale URL by appending
 * format=rationale, which both /api/design/model and /api/property/envelope
 * answer — so the same frame shows a generated scheme or the rule envelope
 * with no special casing.
 */
const viewerSrc = computed(() => {
  if (active.value === -1 && address.value) {
    return `/craftbot-viewer/index.html?model=${encodeURIComponent(envelopeUrl.value)}&label=${encodeURIComponent('Planning envelope')}`
  }
  const r = current.value
  if (!r || r.error) return ''
  return `/craftbot-viewer/index.html?model=${encodeURIComponent(r.modelUrl)}&label=${encodeURIComponent(r.schemeName || r.label)}`
})

// ── address autocomplete ──────────────────────────────────────────────
interface Ac { address: string, context: string }
const acResults = ref<Ac[]>([])
let acTimer: ReturnType<typeof setTimeout> | null = null

function onAddressInput() {
  if (acTimer) clearTimeout(acTimer)
  const q = address.value.trim()
  if (q.length < 3) { acResults.value = []; return }
  acTimer = setTimeout(async () => {
    try {
      const res = await fetch(`/api/property/search?q=${encodeURIComponent(q)}`)
      if (!res.ok) return
      const data = await res.json()
      acResults.value = (data.results || []).map((r: any) => ({
        address: r.address,
        context: [r.suburbname, r.lga_name].filter(Boolean).join(', '),
      }))
    } catch { /* an empty list is the right failure here */ }
  }, 250)
}
function dismissAc() { setTimeout(() => { acResults.value = [] }, 180) }
function selectAddress(r: Ac) { address.value = r.address; acResults.value = []; loadBrief() }
function pickSample(s: { address: string }) { address.value = s.address; acResults.value = []; loadBrief() }

// ── the brief, fetched as soon as an address is settled ───────────────
async function loadBrief() {
  brief.value = null
  error.value = ''
  if (!address.value) return
  try {
    const res = await fetch(`/api/design/brief?address=${encodeURIComponent(address.value)}&use=${encodeURIComponent(use.value)}&storeys=${storeys.value}`)
    const data = await res.json()
    if (!res.ok) { error.value = data.statusMessage || data.message || 'Could not load the site brief.'; return }
    brief.value = data
  } catch (e: any) {
    error.value = e?.message ?? 'Could not load the site brief.'
  }
}

watch([use, storeys], () => { if (address.value) loadBrief() })

// ── generation ────────────────────────────────────────────────────────
async function generate() {
  busy.value = true
  error.value = ''
  results.value = []
  active.value = 0
  busyText.value = `Designing ${variants.value.length} scheme${variants.value.length === 1 ? '' : 's'}…`
  try {
    const res = await fetch('/api/design/generate', {
      method: 'POST',
      headers: { 'content-type': 'application/json' },
      body: JSON.stringify({
        address: address.value,
        use: use.value,
        storeys: storeys.value,
        model: modelKey.value,
        variants: variants.value,
      }),
    })
    const data = await res.json()
    if (!res.ok) {
      error.value = data.statusMessage || data.message || `Generation failed (${res.status}).`
      return
    }
    brief.value = data.brief
    modelName.value = data.modelName
    results.value = data.variants
  } catch (e: any) {
    error.value = e?.message ?? 'Generation failed.'
  } finally {
    busy.value = false
  }
}

useHead({ title: 'Design Lab — Australian Planning Library' })
</script>

