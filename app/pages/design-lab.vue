<!--
  /design-lab — generative design, tested against the controls

  The rule layer already answers "what does this lot allow" — that is the
  envelope at /api/property/envelope, and the 3D viewer at /craftbot shows it.
  This page asks the next question: given that envelope, what would you build?

  A model is asked for a scheme; this app turns the scheme into geometry and
  then measures it against the same controls the envelope was drawn from. The
  measurements are the point. A generated massing on its own is a picture, and
  a picture of a building that breaches its own setback is worse than nothing.

  Nothing here writes to the graph and nothing here is advice. It shares the
  vendored viewer with /craftbot but leaves that page untouched: the models are
  served from /api/design/model and loaded through the same ?model= deep link
  the envelope already uses.
-->

